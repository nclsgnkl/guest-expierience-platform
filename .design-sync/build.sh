#!/usr/bin/env bash
# Build the claude.ai/design upload bundle for the Guest Experience Platform.
#
# This repo is an Angular application, not a React component library, so the
# /design-sync converter does not apply: there is no compiled component bundle
# that Claude Design's React runtime could render. What DOES transfer is the
# design system itself — the two-layer token stylesheet, the self-hosted type,
# and the written design spec — so this script assembles exactly that.
#
# Everything here is copied verbatim from frontend/src with ONE adaptation:
# the @font-face URLs are rewritten from the Angular app's absolute
# /assets/fonts/... paths to paths relative to the bundle's own layout.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=ds-bundle
rm -rf "$OUT"
mkdir -p "$OUT"/{tokens,fonts,guidelines/screens,guidelines/screens-inhouse}

# --- Stylesheets -----------------------------------------------------------
cp frontend/src/styles/tokens.css "$OUT/tokens/tokens.css"
cp frontend/src/styles/global.css "$OUT/tokens/global.css"

# The one adaptation: absolute app asset paths -> bundle-relative paths.
# url() resolves against the stylesheet that contains it, i.e. tokens/global.css.
sed -i "s#url('/assets/fonts/plus-jakarta-sans/#url('../fonts/#g" "$OUT/tokens/global.css"

# Fail loudly rather than shipping silently-unstyled type.
if grep -q "/assets/fonts/" "$OUT/tokens/global.css"; then
  echo "ERROR: unrewritten font path in tokens/global.css" >&2; exit 1
fi

cat > "$OUT/styles.css" <<'CSS'
/* Entry point. Rendered designs receive only this file's transitive @import
   closure, so every stylesheet that matters has to be reachable from here.
   Order is deliberate: tokens first, then the global layer that consumes them. */
@import "tokens/tokens.css";
@import "tokens/global.css";
CSS

# --- Fonts -----------------------------------------------------------------
cp frontend/src/assets/fonts/plus-jakarta-sans/*.woff2 "$OUT/fonts/"

# --- Guidelines ------------------------------------------------------------
# The as-built design record. _template.md and extraction-log.md are process
# artifacts of the Figma import, not guidance for building screens.
cp docs/design/tokens.md docs/design/design-sheet.md docs/design/dark-theme.md "$OUT/guidelines/"
cp docs/design/screens/home.md "$OUT/guidelines/screens/"
cp docs/design/screens-inhouse/*.md "$OUT/guidelines/screens-inhouse/"

# --- README ----------------------------------------------------------------
# The conventions header is the hand-authored part; the index below it is
# generated so it can never drift from what actually shipped.
cat .design-sync/conventions.md > "$OUT/README.md"
{
  echo
  echo "---"
  echo
  echo "## What is in this project"
  echo
  echo '```'
  find "$OUT" -type f | sed "s#^$OUT/##" | sort | sed 's/^/  /'
  echo '```'
  echo
  echo "_Generated by \`.design-sync/build.sh\` from the repo. Do not hand-edit"
  echo "the section above the rule either — it comes from \`.design-sync/conventions.md\`._"
} >> "$OUT/README.md"

echo "Built $OUT: $(find "$OUT" -type f | wc -l) files, $(du -sh "$OUT" | cut -f1)"
